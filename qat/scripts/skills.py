#!/usr/bin/env python3
"""Generate the Claude skills from their sources, check them, and package a release.

QAT-Kits is the source of record for the QAT skills Claude runs (DEC-192, DEC-193).
Each skill's source is `qat/tools/<name>.skill.md`: frontmatter (`name`, `version`,
`description`, optionally `kind: runner`) and the skill text. This script writes
`qat/runtimes/claude/<name>/SKILL.md` from it, stamped with the version, the source's
sha256 and a "generated from" line, and records everything in
`qat/runtimes/claude/skills.lock.json`. The `qat` runner skill (`kind: runner`) also
gets the runner files: scripts/qat.py, INDEX.md, tools/*.qat.md and cases/.

    python3 -I qat/scripts/skills.py build               # regenerate everything
    python3 -I qat/scripts/skills.py check [--base REF]  # CI: stale files, version and eval gates
    python3 -I qat/scripts/skills.py package OUT_DIR     # release bundle (plugin + per-skill zips)

Standard library only. Exit code 1 means at least one error.
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys
import zipfile
from pathlib import Path

QAT = Path(__file__).resolve().parent.parent          # .../qat
REPO = QAT.parent
TOOLS = QAT / "tools"
OUT = QAT / "runtimes" / "claude"
LOCK = OUT / "skills.lock.json"
BUNDLE_VERSION = OUT / "BUNDLE_VERSION"
PLUGIN = "qat-kit"
MARK = "<!-- GENERATED by qat/scripts/skills.py"
SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$")
ZIP_TIME = (2026, 1, 1, 0, 0, 0)


def rel(p: Path) -> str:
    return p.relative_to(REPO).as_posix()


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def parse_source(text: str, where: str):
    """Return (meta dict, frontmatter lines without version/kind, body). Raises ValueError."""
    if not text.startswith("---\n") or "\n---\n" not in text[3:]:
        raise ValueError(f"{where}: must start with a --- frontmatter block")
    end = text.index("\n---\n", 3)
    lines = text[4:end].split("\n")
    meta, keep = {}, []
    for ln in lines:
        m = re.match(r"^([a-z_]+):\s*(.*)$", ln)
        if not m:
            raise ValueError(f"{where}: frontmatter line is not 'key: value': {ln!r}")
        k, v = m.group(1), m.group(2).strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        meta[k] = v
        if k not in ("version", "kind"):
            keep.append(ln)
    for k in ("name", "version", "description"):
        if not meta.get(k):
            raise ValueError(f"{where}: frontmatter needs '{k}'")
    if not SEMVER.match(meta["version"]):
        raise ValueError(f"{where}: version {meta['version']!r} is not semver (1.2.3 or 1.2.3-tag)")
    if meta.get("kind", "skill") not in ("skill", "runner"):
        raise ValueError(f"{where}: kind must be 'skill' or 'runner'")
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", meta["name"]):
        raise ValueError(f"{where}: name must be lowercase-hyphenated")
    return meta, keep, text[end + 5:]


def version_key(v: str):
    m = SEMVER.match(v)
    major, minor, patch, pre = int(m[1]), int(m[2]), int(m[3]), m[4]
    # a pre-release sorts below its release (semver); pre-release tags compare as text
    return (major, minor, patch, 0 if pre else 1, pre or "")


def sources(tools: Path = TOOLS):
    """Yield (path, meta, keep, body) for every skill source."""
    for p in sorted(tools.glob("*.skill.md")):
        meta, keep, body = parse_source(p.read_text(encoding="utf-8"), rel(p))
        if p.name != f"{meta['name']}.skill.md":
            raise ValueError(f"{rel(p)}: filename must be {meta['name']}.skill.md")
        yield p, meta, keep, body


def runner_files():
    """Files the runner skill carries besides SKILL.md: {path inside skill: source path}."""
    out = {"scripts/qat.py": QAT / "scripts" / "qat.py", "INDEX.md": QAT / "INDEX.md"}
    for p in sorted((QAT / "tools").glob("*.qat.md")):
        out[f"tools/{p.name}"] = p
    for p in sorted((QAT / "cases").rglob("*")):
        if p.is_file():
            out[f"cases/{p.relative_to(QAT / 'cases').as_posix()}"] = p
    return out


def render():
    """Everything `build` writes: {repo-relative path: bytes}, plus the lock dict."""
    files, skills = {}, {}
    bundle = BUNDLE_VERSION.read_text(encoding="utf-8").strip()
    if not SEMVER.match(bundle):
        raise ValueError(f"{rel(BUNDLE_VERSION)}: {bundle!r} is not semver")
    for p, meta, keep, body in sources():
        raw = p.read_bytes()
        stamp = (f"{MARK} from {rel(p)}. Do not edit: edit the source and run "
                 f"`python3 -I qat/scripts/skills.py build`. version: {meta['version']} · "
                 f"source sha256: {sha(raw)} -->\n")
        skill_md = ("---\n" + "\n".join(keep) + "\n---\n" + stamp + body).encode("utf-8")
        d = OUT / meta["name"]
        entry = {"version": meta["version"], "source": rel(p), "source_sha256": sha(raw),
                 "kind": meta.get("kind", "skill"), "files": {}}
        payload = {"SKILL.md": skill_md}
        if meta.get("kind") == "runner":
            for inner, src in runner_files().items():
                payload[inner] = src.read_bytes()
        for inner, b in sorted(payload.items()):
            files[rel(d / inner)] = b
            entry["files"][inner] = sha(b)
        skills[meta["name"]] = entry
    lock = {"_note": "Generated by qat/scripts/skills.py; do not edit.",
            "plugin": PLUGIN, "bundle_version": bundle, "skills": skills}
    files[rel(LOCK)] = (json.dumps(lock, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return files, lock


def generated_dirs():
    """Skill dirs under OUT whose SKILL.md carries the generated marker."""
    for p in sorted(OUT.glob("*/SKILL.md")):
        if MARK in p.read_text(encoding="utf-8"):
            yield p.parent


def build() -> int:
    files, lock = render()
    for d in generated_dirs():                       # drop generated skills whose source is gone
        if d.name not in lock["skills"]:
            for f in sorted(d.rglob("*"), reverse=True):
                f.unlink() if f.is_file() else f.rmdir()
            d.rmdir()
    for d in generated_dirs():                       # drop files a skill no longer carries
        for f in d.rglob("*"):
            if f.is_file() and rel(f) not in files:
                f.unlink()
    for path, b in files.items():
        f = REPO / path
        f.parent.mkdir(parents=True, exist_ok=True)
        if not f.exists() or f.read_bytes() != b:
            f.write_bytes(b)
    print(f"built {len(lock['skills'])} skills, bundle {lock['bundle_version']}")
    return 0


def git(*args) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], check=True,
                          capture_output=True, text=True).stdout


def at_base(base: str, path: str):
    try:
        return subprocess.run(["git", "-C", str(REPO), "show", f"{base}:{path}"], check=True,
                              capture_output=True).stdout.decode("utf-8")
    except subprocess.CalledProcessError:
        return None


def spec_version(text: str, where: str):
    """Version of a skill source or a .qat.md spec (frontmatter 'version:')."""
    m = re.search(r"^version:\s*['\"]?([^'\"\s]+)", text.split("\n---\n", 1)[0], re.M)
    if not m or not SEMVER.match(m.group(1)):
        raise ValueError(f"{where}: no semver 'version:' in frontmatter")
    return m.group(1)


def gate(base: str, errors: list):
    """Version and eval gates for specs changed since `base` (DEC-193: eval-gated changes)."""
    changed = [ln for ln in git("diff", "--name-status", "--no-renames", f"{base}...HEAD").splitlines() if ln]
    # only added or modified files count as a recorded run; deleting an old run records nothing
    evals = [path for status, path in (ln.split("\t", 1) for ln in changed)
             if status in ("A", "M") and path.startswith("qat/eval-runs/")]
    for ln in changed:
        status, path = ln.split("\t", 1)
        m = re.fullmatch(r"qat/tools/([a-z0-9-]+)\.(skill|qat)\.md", path)
        if not m or status != "M":
            continue                                  # new specs have no prior version to gate against
        name = m.group(1)
        old, new = at_base(base, path), (REPO / path).read_text(encoding="utf-8")
        try:
            vo, vn = spec_version(old, f"{base}:{path}"), spec_version(new, path)
            if version_key(vn) <= version_key(vo):
                errors.append(f"VERSION_NOT_BUMPED {path}: changed but version {vn} is not above {vo}")
        except ValueError as e:
            errors.append(f"SPEC_INVALID {e}")
        recorded = [p for p in evals if any(c == name or c.startswith(name + ".") or c.startswith(name + "-")
                                            for c in p.split("/")[2:])]
        if not recorded:
            has_cases = (QAT / "cases" / f"{name}.eval.yaml").exists()
            hint = ("run its cases with `qat.py eval` and commit the outputs and RESULTS under "
                    f"qat/eval-runs/<date>/{name}/" if has_cases else
                    f"it has no cases yet: add qat/cases/{name}.eval.yaml, run it, and record the run "
                    f"under qat/eval-runs/<date>/{name}/")
            errors.append(f"EVAL_NOT_RECORDED {path}: changed with no eval run recorded in this change; {hint}")
    old_lock = at_base(base, rel(LOCK))
    if old_lock:
        old = json.loads(old_lock)
        _, new = render()
        if old["skills"] != new["skills"] and version_key(new["bundle_version"]) <= version_key(old["bundle_version"]):
            errors.append(f"BUNDLE_NOT_BUMPED {rel(BUNDLE_VERSION)}: skills changed but bundle version "
                          f"{new['bundle_version']} is not above {old['bundle_version']}")


def check(base) -> int:
    errors = []
    try:
        files, lock = render()
    except ValueError as e:
        print(f"ERROR SPEC_INVALID {e}")
        return 1
    for path, b in files.items():
        f = REPO / path
        if not f.exists():
            errors.append(f"STALE {path}: missing; run `python3 -I qat/scripts/skills.py build`")
        elif f.read_bytes() != b:
            errors.append(f"STALE {path}: differs from its source; run `python3 -I qat/scripts/skills.py build` "
                          "(never edit a generated file)")
    for d in generated_dirs():
        for f in d.rglob("*"):
            if f.is_file() and rel(f) not in files:
                errors.append(f"STALE {rel(f)}: generated file with no source; run build")
    if base:
        gate(base, errors)
    for e in errors:
        print(f"ERROR {e}")
    print(f"check: {len(lock['skills'])} skills, bundle {lock['bundle_version']}, {len(errors)} error(s)")
    return 1 if errors else 0


def write_zip(path: Path, entries: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(entries):
            info = zipfile.ZipInfo(name, ZIP_TIME)
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, entries[name])


def package(out: Path) -> int:
    if check(None):
        print("package: refusing to package stale skills")
        return 1
    files, lock = render()
    bundle = lock["bundle_version"]
    manifest = {"name": PLUGIN, "version": bundle,
                "description": "QAT-Kit conversational tools as Claude skills, generated from eraevous/QAT-Kits.",
                "repository": "https://github.com/eraevous/QAT-Kits"}
    plugin = {".claude-plugin/plugin.json": (json.dumps(manifest, indent=2) + "\n").encode()}
    for name, entry in lock["skills"].items():
        single = {}
        for inner in entry["files"]:
            b = files[rel(OUT / name / inner)]
            plugin[f"skills/{name}/{inner}"] = b
            single[f"{name}/{inner}"] = b
        write_zip(out / "skills" / f"{name}-{entry['version']}.zip", single)
    for inner, b in plugin.items():
        f = out / PLUGIN / inner
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(b)
    write_zip(out / f"{PLUGIN}-{bundle}.zip", plugin)
    (out / "skills.lock.json").write_bytes(files[rel(LOCK)])
    sums = sorted(p for p in out.rglob("*.zip"))
    (out / "SHA256SUMS").write_text("".join(f"{sha(p.read_bytes())}  {p.relative_to(out).as_posix()}\n" for p in sums))
    print(f"packaged {PLUGIN} {bundle}: {out / f'{PLUGIN}-{bundle}.zip'} and {len(lock['skills'])} skill zips")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    c = sub.add_parser("check")
    c.add_argument("--base", help="git ref to gate against (version bumps, recorded evals)")
    pk = sub.add_parser("package")
    pk.add_argument("out", type=Path)
    a = ap.parse_args(argv)
    try:
        if a.cmd == "build":
            return build()
        if a.cmd == "check":
            return check(a.base)
        return package(a.out)
    except ValueError as e:
        print(f"ERROR SPEC_INVALID {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
